/** Platform-specific mailbox lifecycle, kept separate from Svelte for deterministic tests. */
import { isNativeMobile, requestApi } from './transport';

export const GMAIL_READONLY_SCOPE = 'https://www.googleapis.com/auth/gmail.readonly';

/** Sanitized, process-local account metadata. Never persist or log labels. */
export interface MailboxAccount {
  id: string;
  label: string;
  connected: boolean;
  lastSuccessfulScan: string | null;
  reconnectRequired: boolean;
  error?: string;
}

export interface GmailStatus {
  enabled: boolean;
  configured: boolean;
  accounts: MailboxAccount[];
  authorizationPending?: boolean;
}

/** Display state shared by Android and the desktop Gmail panel. */
export interface MailboxState {
  accounts: MailboxAccount[];
  backgroundStatus: string;
  overlayGranted: boolean;
  overlayActive: boolean;
  notificationsGranted: boolean;
  busy: boolean;
  error: string | null;
  loading: boolean;
  enabled: boolean;
  configured: boolean;
  authorizationPending: boolean;
  authorizationExpiresAt: string | null;
  operation: 'authorize' | 'reconnect' | 'disconnect' | 'scan' | null;
  notice: string | null;
}

/** Empty panel state before the first account response. */
export function emptyMailbox(): MailboxState {
  return {
    accounts: [], backgroundStatus: 'Loading…', overlayGranted: false, overlayActive: false,
    notificationsGranted: false, busy: false, error: null, loading: true,
    enabled: false, configured: false, authorizationPending: false,
    authorizationExpiresAt: null, operation: null, notice: null
  };
}

function record(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function account(value: unknown): value is MailboxAccount {
  return record(value) && typeof value.id === 'string' && value.id.length > 0 &&
    typeof value.label === 'string' && typeof value.connected === 'boolean' &&
    (value.lastSuccessfulScan === null || typeof value.lastSuccessfulScan === 'string') &&
    typeof value.reconnectRequired === 'boolean';
}

// Exact codes generated by Android's GoogleAuthorizationError; never display provider text.
const nativeAuthorizationMessages: Readonly<Record<string, string>> = {
  google_auth_user_cancelled: 'Google authorization was cancelled.',
  google_auth_configuration: 'Google authorization configuration error. Check the Android OAuth package name and signing certificate.',
  google_auth_transient: 'Google authorization is temporarily unavailable. Check your network and Google Play Services, then retry.',
  google_auth_workspace_policy_denied: 'Google Workspace policy blocks authorization. Contact your administrator.',
  google_auth_consent_denied: 'Google did not grant Gmail read-only access. Check consent-screen and test-user access, then retry.',
  google_auth_unknown: 'Google authorization failed without a specific reason. Check Android OAuth configuration, account access, and Google Play Services.'
};

async function nativeOperationFailure(response: Response): Promise<string> {
  try {
    const value: unknown = await response.json();
    if (record(value) && typeof value.code === 'string' &&
        Object.hasOwn(nativeAuthorizationMessages, value.code)) {
      return nativeAuthorizationMessages[value.code];
    }
  } catch { /* Missing or malformed bodies do not provide a trusted error category. */ }
  return `Mailbox operation failed (HTTP ${response.status}).`;
}

/** Select native routes only for the injected Android bridge. */
export function createMailbox(
  update: (state: MailboxState) => void,
  fetcher: typeof fetch = requestApi,
  onAccountsChanged: () => void = () => {},
  native = isNativeMobile(),
  onDataWiped: (generation?: number) => void = () => {}
) {
  return native
    ? createNativeMailbox(update, fetcher, onAccountsChanged, onDataWiped)
    : createDesktopMailbox(update, fetcher, onAccountsChanged, onDataWiped);
}

function resetGeneration(value: Record<string, unknown>): number | undefined {
  return Number.isSafeInteger(value.resetGeneration) && (value.resetGeneration as number) >= 0
    ? value.resetGeneration as number : undefined;
}

/** The Android shell completes OAuth before resolving an add/reconnect request. */
function createNativeMailbox(
  update: (state: MailboxState) => void,
  fetcher: typeof fetch,
  onAccountsChanged: () => void,
  onDataWiped: (generation?: number) => void
) {
  let state = emptyMailbox();
  let disposed = false;
  let generation = 0;
  const abort = new AbortController();
  const publish = (changes: Partial<MailboxState>) => {
    if (disposed) return;
    state = { ...state, ...changes };
    update(state);
  };

  const refresh = async () => {
    const request = ++generation;
    try {
      const response = await fetcher('/api/v1/accounts', { signal: abort.signal });
      if (!response.ok) throw new Error(`Mailbox unavailable (HTTP ${response.status}).`);
      const value: unknown = await response.json();
      if (!record(value) || !Array.isArray(value.accounts) || !value.accounts.every(account) ||
          typeof value.backgroundStatus !== 'string' || typeof value.overlayGranted !== 'boolean' ||
          typeof value.overlayActive !== 'boolean' || typeof value.notificationsGranted !== 'boolean') {
        throw new Error('Invalid mailbox response.');
      }
      if (request === generation) publish({
        accounts: value.accounts, backgroundStatus: value.backgroundStatus,
        overlayGranted: value.overlayGranted, overlayActive: value.overlayActive,
        notificationsGranted: value.notificationsGranted, error: null,
        loading: false, enabled: true, configured: true
      });
    } catch (error) {
      if (request === generation) publish({
        error: error instanceof Error ? error.message : 'Mailbox unavailable.', loading: false
      });
    }
  };

  const change = async (path: string, method: 'POST' | 'DELETE', body?: string) => {
    if (disposed || state.busy) return;
    publish({ busy: true, error: null });
    let failureMessage = 'Mailbox operation failed.';
    try {
      const response = await fetcher(path, { method, signal: abort.signal, ...(body ? { body } : {}) });
      if (!response.ok) {
        failureMessage = await nativeOperationFailure(response);
        throw new Error();
      }
      if (response.status !== 204) {
        const value: unknown = await response.json();
        if (!disposed && method === 'DELETE' && record(value) && value.dataWiped === true)
          onDataWiped(resetGeneration(value));
        if (record(value) && value.ok === false) throw new Error('Mailbox operation failed.');
      }
      if (!disposed) {
        // Reload history as soon as the native operation completes, even if
        // the subsequent account-status request is slow or unavailable.
        onAccountsChanged();
        await refresh();
      }
    } catch {
      publish({ error: failureMessage });
    } finally {
      publish({ busy: false });
    }
  };
  const onReturn = () => { if (!disposed) void refresh(); };
  const onVisible = () => { if (document.visibilityState === 'visible') onReturn(); };
  window.addEventListener('focus', onReturn);
  document.addEventListener('visibilitychange', onVisible);
  const timer = setInterval(onVisible, 30_000);

  return {
    refresh,
    add: () => change('/api/v1/accounts/add', 'POST'),
    reconnect: (id: string) => change(`/api/v1/accounts/${encodeURIComponent(id)}/reconnect`, 'POST'),
    disconnect: (id: string) => change(`/api/v1/accounts/${encodeURIComponent(id)}`, 'DELETE'),
    scan: () => change('/api/v1/scan/now', 'POST', JSON.stringify({ lookbackDays: 7, useLuna: false })),
    requestOverlay: () => change('/api/v1/overlay/permission', 'POST'),
    stopOverlay: () => change('/api/v1/overlay/stop', 'POST'),
    dispose: () => {
      disposed = true;
      abort.abort();
      clearInterval(timer);
      window.removeEventListener('focus', onReturn);
      document.removeEventListener('visibilitychange', onVisible);
    }
  };
}

function gmailStatus(value: unknown): value is GmailStatus {
  return record(value) && typeof value.enabled === 'boolean' &&
    typeof value.configured === 'boolean' && Array.isArray(value.accounts) &&
    value.accounts.every((item) => account(item) &&
      (item.error === undefined || typeof item.error === 'string')) &&
    new Set(value.accounts.map((item) => item.id)).size === value.accounts.length &&
    (value.authorizationPending === undefined || typeof value.authorizationPending === 'boolean');
}

interface GmailScanResult {
  fetchedCount: number;
  newMessagesAnalyzed: number;
  animationsTriggered: number;
  successfulAccounts: number;
  failedAccounts: number;
  errors: { id: string; error: string }[];
}

function gmailScanResult(value: unknown): value is GmailScanResult {
  return record(value) && value.ok !== false && !Object.hasOwn(value, 'error') &&
    ['fetchedCount', 'newMessagesAnalyzed', 'animationsTriggered', 'successfulAccounts', 'failedAccounts']
      .every((key) => Number.isSafeInteger(value[key]) && (value[key] as number) >= 0) &&
    Array.isArray(value.errors) && value.errors.every((item) =>
      record(item) && typeof item.id === 'string' && typeof item.error === 'string');
}

/** Never navigate to an arbitrary host, user-info URL, or elevated Gmail scope. */
function authorization(value: unknown): { url: string; expiresAt: string } | null {
  if (!record(value) || typeof value.authorizationUrl !== 'string' ||
      typeof value.expiresAt !== 'string') return null;
  try {
    const url = new URL(value.authorizationUrl);
    const expires = Date.parse(value.expiresAt);
    if (url.protocol !== 'https:' || url.hostname !== 'accounts.google.com' ||
        url.port || url.username || url.password || url.hash ||
        url.searchParams.getAll('scope').length !== 1 ||
        url.searchParams.get('scope') !== GMAIL_READONLY_SCOPE ||
        !Number.isFinite(expires) || expires <= Date.now() ||
        expires > Date.now() + 305_000) return null;
    return { url: url.href, expiresAt: value.expiresAt };
  } catch { return null; }
}

function createDesktopMailbox(
  update: (state: MailboxState) => void,
  fetcher: typeof fetch,
  onAccountsChanged: () => void,
  onDataWiped: (generation?: number) => void
) {
  let state = emptyMailbox();
  let disposed = false;
  let generation = 0;
  let expiryTimer: ReturnType<typeof setTimeout> | undefined;
  let popup: Window | null = null;
  const abort = new AbortController();
  const publish = (changes: Partial<MailboxState>) => {
    if (disposed) return;
    state = { ...state, ...changes };
    update(state);
  };
  const closePopup = () => {
    try { popup?.close(); } catch { /* The browser may already have closed the tab. */ }
    popup = null;
  };
  const setPending = (pending: boolean, expiresAt: string | null = null) => {
    clearTimeout(expiryTimer);
    if (expiresAt && Date.parse(expiresAt) <= Date.now()) expiresAt = null;
    publish({ authorizationPending: pending, authorizationExpiresAt: pending ? expiresAt : null });
    if (pending && expiresAt) {
      expiryTimer = setTimeout(() => {
        publish({
          authorizationPending: false, authorizationExpiresAt: null,
          notice: 'Gmail authorization expired. Click Sign in to Gmail or Reconnect to try again.'
        });
        void refresh();
      }, Math.max(0, Date.parse(expiresAt) - Date.now()));
    }
  };
  const refresh = async () => {
    if (disposed) return;
    const request = ++generation;
    try {
      const response = await fetcher('/api/v1/gmail/accounts', { signal: abort.signal });
      if (!response.ok) throw new Error();
      const value: unknown = await response.json();
      if (!gmailStatus(value)) throw new Error();
      if (disposed || request !== generation) return;
      const wasPending = state.authorizationPending;
      // Copy only display metadata. Raw errors and unexpected response fields never reach UI state.
      const accounts = value.accounts.map((item) => ({
        id: item.id, label: item.label, connected: item.connected,
        reconnectRequired: item.reconnectRequired, lastSuccessfulScan: item.lastSuccessfulScan,
        ...(item.error ? { error: 'Gmail could not finish this account’s scan. Try Scan now or Reconnect.' } : {})
      }));
      const changed = JSON.stringify(state.accounts) !== JSON.stringify(accounts);
      setPending(value.authorizationPending === true, state.authorizationExpiresAt);
      publish({
        accounts, enabled: value.enabled, configured: value.configured, loading: false,
        error: null,
        ...(wasPending && !value.authorizationPending
          ? { notice: 'Authorization finished or was cancelled. Check the Gmail connection status below.' }
          : {})
      });
      if (changed || (wasPending && !value.authorizationPending)) onAccountsChanged();
    } catch {
      if (request === generation) publish({
        loading: false, error: 'Gmail status unavailable. Check the local daemon and click Refresh Gmail status.'
      });
    }
  };
  const ready = () => !disposed && !state.loading && state.enabled && state.configured &&
    !state.busy && !state.authorizationPending;

  const authorize = async (id?: string) => {
    if (!ready()) return;
    // Reserve the browser tab within the click gesture, before awaiting the daemon.
    try {
      popup = window.open('about:blank', '_blank');
      if (!popup || popup.closed) throw new Error();
      popup.opener = null;
    } catch {
      closePopup();
      publish({ error: 'Google sign-in popup blocked. Allow popups for this local dashboard, then click Sign in to Gmail or Reconnect again.' });
      return;
    }
    ++generation;
    publish({ busy: true, operation: id ? 'reconnect' : 'authorize', error: null, notice: null });
    // A lost response can still have started OAuth. Keep the guard until status or expiry resolves it.
    setPending(true, new Date(Date.now() + 300_000).toISOString());
    try {
      const path = id
        ? `/api/v1/gmail/accounts/${encodeURIComponent(id)}/reconnect`
        : '/api/v1/gmail/authorize';
      const response = await fetcher(path, { method: 'POST', signal: abort.signal });
      if (!response.ok) {
        if (response.status !== 409) setPending(false);
        closePopup();
        await refresh();
        publish({ error: response.status === 409
          ? 'Gmail authorization is already pending. Finish Google sign-in or wait for it to expire, then refresh Gmail status.'
          : 'Gmail authorization could not start. Check daemon configuration and try again.' });
        return;
      }
      const result = authorization(await response.json());
      if (disposed) { closePopup(); return; }
      if (!result) throw new Error();
      ++generation;
      setPending(true, result.expiresAt);
      if (!popup || popup.closed) throw new Error();
      popup.location.replace(result.url);
      popup = null; // The external sign-in tab now belongs to the user.
      publish({ notice: 'Complete read-only Google sign-in in the browser tab, then return here. You can close that tab when finished.' });
    } catch {
      closePopup();
      publish({ error: 'Google sign-in could not open safely. Refresh Gmail status or wait five minutes, then try Sign in to Gmail or Reconnect again.' });
    } finally {
      publish({ busy: false, operation: null });
    }
  };

  const change = async (path: string, operation: 'disconnect' | 'scan') => {
    if (!ready() || (operation === 'scan' &&
        !state.accounts.some((item) => item.connected && !item.reconnectRequired))) return;
    ++generation;
    publish({ busy: true, operation, error: null, notice: null });
    let failed = false;
    let result: GmailScanResult | undefined;
    let disconnectNotice: string | undefined;
    try {
      const response = await fetcher(path, {
        method: operation === 'disconnect' ? 'DELETE' : 'POST', signal: abort.signal
      });
      if (operation === 'scan') {
        if (!response.ok) throw new Error();
        const value: unknown = await response.json();
        if (!gmailScanResult(value)) throw new Error();
        result = value;
      } else {
        const value: unknown = await response.json();
        if (!disposed && record(value) && value.dataWiped === true) onDataWiped(resetGeneration(value));
        if (!response.ok || !record(value) || value.ok !== true || value.dataWiped !== true ||
            typeof value.message !== 'string' || Object.hasOwn(value, 'error')) throw new Error();
        disconnectNotice = value.message;
      }
      if (!disposed) onAccountsChanged();
    } catch { failed = true; }
    await refresh();
    publish({
      busy: false, operation: null,
      ...(failed
        ? { error: operation === 'scan'
          ? 'Gmail scan failed. Check connection status, reconnect if needed, and try Scan now again.'
          : 'Gmail disconnect failed. Refresh Gmail status and try Disconnect again.' }
        : result
          ? {
            notice: `Gmail scan ${result.failedAccounts ? 'incomplete' : 'complete'}: ` +
              `${result.newMessagesAnalyzed} added / ${result.fetchedCount} fetched; ` +
              `${result.successfulAccounts} accounts scanned, ${result.animationsTriggered} animations triggered.`,
            ...(result.failedAccounts ? {
              error: `Gmail could not scan ${result.failedAccounts} account${result.failedAccounts === 1 ? '' : 's'}. ` +
                'Check connection status, reconnect if needed, and try Scan now again.'
            } : {})
          }
          : { notice: disconnectNotice ?? 'Signed out of Gmail. All communication data wiped.' })
    });
  };

  const onReturn = () => { if (!disposed) void refresh(); };
  const onVisible = () => { if (document.visibilityState === 'visible') onReturn(); };
  window.addEventListener('focus', onReturn);
  document.addEventListener('visibilitychange', onVisible);
  const timer = setInterval(onVisible, 30_000);
  const source = typeof EventSource === 'undefined' ? null : new EventSource('/api/v1/gmail/events');
  const onStatus = (event: Event) => {
    try {
      const value: unknown = JSON.parse((event as MessageEvent).data);
      if (record(value) && value.changed === true && Object.keys(value).length === 1) onReturn();
    } catch { /* Status notifications contain no account data. */ }
  };
  source?.addEventListener('gmail-status', onStatus);
  // EventSource reconnects itself; refresh once it returns after a daemon restart.
  source?.addEventListener('open', onReturn);
  return {
    refresh,
    add: () => authorize(),
    reconnect: (id: string) => authorize(id),
    disconnect: (id: string) => change(`/api/v1/gmail/accounts/${encodeURIComponent(id)}`, 'disconnect'),
    scan: () => change('/api/v1/gmail/scan', 'scan'),
    requestOverlay: async () => {},
    stopOverlay: async () => {},
    dispose: () => {
      disposed = true;
      abort.abort();
      closePopup();
      clearInterval(timer);
      clearTimeout(expiryTimer);
      source?.removeEventListener('gmail-status', onStatus);
      source?.removeEventListener('open', onReturn);
      source?.close();
      window.removeEventListener('focus', onReturn);
      document.removeEventListener('visibilitychange', onVisible);
    }
  };
}
